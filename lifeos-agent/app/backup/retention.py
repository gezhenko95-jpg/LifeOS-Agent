"""
Чистая функция ротации бэкапов — без Drive и без файловой системы, на
входе имена, на выходе имена. Тестируется без моков (по образцу
app/insights/calculations.py).
"""


def files_to_delete(names: list[str], keep: int) -> list[str]:
    """Какие бэкапы удалить, чтобы осталось `keep` самых свежих.

    Свежесть определяется по ИМЕНИ, а не по времени создания на Диске:
    имя содержит дату (lifeos-2026-08-15.sql.gz), поэтому обычная
    сортировка строк даёт хронологический порядок и не зависит от того,
    в каком порядке Drive вернул список.

    keep <= 0 трактуется как "оставить всё": обнулить настройку и
    случайно снести все бэкапы разом — цена ошибки слишком высокая,
    чтобы позволять это молча.
    """
    if keep <= 0:
        return []
    ordered = sorted(names, reverse=True)
    return ordered[keep:]
