def character_sheet(persona: Persona) -> str:
    return _CHARACTER_SHEETS.get(persona, _CHARACTER_SHEETS[DEFAULT_PERSONA])


def persona_name(persona: Persona) -> str:
    return PERSONA_NAMES.get(persona, PERSONA_NAMES[DEFAULT_PERSONA])


def build_insight_prompt(persona: Persona, task_instruction: str) -> str:
    """Характер-лист + конкретное задание для AI-вставки. Единая точка
    сборки system-промпта — без неё каждый из пяти файлов собирал бы
    строку конкатенацией сам, дублируя один и тот же паттерн."""
    return f"{character_sheet(persona)}\n\n{task_instruction}"
